from datetime import date, timedelta

# PROJECT 15 - LIBRARY SYSTEM

books = [
    ["Harry Potter", "J.K. Rowling", "Available"],
    ["Matilda", "Roald Dahl", "Available"],
    ["The Hobbit", "J.R.R. Tolkien", "Available"],
    ["Wonder", "R.J. Palacio", "Available"]
]

borrowed = []


# Show all books
def show_books():
    for book in books:
        print(book[0], "-", book[1], "-", book[2])


# Search for a book
def search_book():
    name = input("Enter title or author: ").lower()
    found = False

    for book in books:
        if name in book[0].lower() or name in book[1].lower():
            print(book[0], "-", book[1], "-", book[2])
            found = True

    if found == False:
        print("Book not found")


# Borrow a book
def borrow_book():
    name = input("Enter book title: ").lower()

    for book in books:
        if book[0].lower() == name:
            if book[2] == "Available":
                student = input("Enter your name: ")
                today = date.today()
                due = today + timedelta(days=14)

                book[2] = "Borrowed"
                borrowed.append([book[0], student, today, due])

                print("Book borrowed successfully!")
                print("Borrow date:", today)
                print("Return date:", due)
            else:
                print("Book already borrowed")
            return

    print("Book not found")


# Return a book
def return_book():
    name = input("Enter book title: ").lower()

    for book in books:
        if book[0].lower() == name:
            if book[2] == "Borrowed":
                book[2] = "Available"

                for record in borrowed:
                    if record[0].lower() == name:
                        borrowed.remove(record)
                        break

                print("Book returned successfully!")
            else:
                print("Book was not borrowed")
            return

    print("Book not found")


# Main menu
while True:
    print("\n===== LIBRARY SYSTEM =====")
    print("1. Show all books")
    print("2. Search book")
    print("3. Borrow book")
    print("4. Return book")
    print("5. Available books")
    print("6. Borrowed books")
    print("7. Overdue books")
    print("8. Summary report")
    print("9. Exit")

    choice = input("Enter choice: ")

    if choice == "1":
        show_books()

    elif choice == "2":
        search_book()

    elif choice == "3":
        borrow_book()

    elif choice == "4":
        return_book()

    elif choice == "5":
        for book in books:
            if book[2] == "Available":
                print(book[0])

    elif choice == "6":
        for record in borrowed:
            print("Book:", record[0])
            print("Student:", record[1])
            print("Borrowed:", record[2])
            print("Return by:", record[3])

    elif choice == "7":
        overdue = 0
        for record in borrowed:
            if date.today() > record[3]:
                print("Overdue:", record[0])
                overdue += 1

        if overdue == 0:
            print("No overdue books")

    elif choice == "8":
        available = 0
        overdue = 0

        for book in books:
            if book[2] == "Available":
                available += 1

        for record in borrowed:
            if date.today() > record[3]:
                overdue += 1

        print("Total books:", len(books))
        print("Available books:", available)
        print("Borrowed books:", len(borrowed))
        print("Overdue books:", overdue)

    elif choice == "9":
        print("Goodbye!")
        break

    else:
        print("Invalid choice")

